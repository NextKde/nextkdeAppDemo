#!/usr/bin/env python3
"""Bake the pinned Framework7 font plus NextKde extensions. Run in a VM/CI.
Dependencies: fonttools==4.61.1 skia-pathops==0.9.1. No system font installation.
"""
from fontTools.ttLib.tables.ttProgram import Program
from array import array
from fontTools.ttLib.tables._g_l_y_f import Glyph, GlyphCoordinates
import hashlib
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path
import pathops

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'shared/Icons'
UPSTREAM = HERE / 'Framework7Icons-Regular.ttf'
font = TTFont(UPSTREAM, recalcTimestamp=False)
names = json.loads((HERE / 'upstream-names.json').read_text())
extensions = json.loads((HERE / 'extensions.json').read_text())
aliases = json.loads((HERE / 'aliases.json').read_text())
# Stable upstream ordering is committed; append on upgrades, never sort/reindex.
codepoints = {name: 0xf0000 + i for i, name in enumerate(names)}
order = list(font.getGlyphOrder())
for name, spec in extensions.items():
    glyph_name = 'nk_' + name
    if 'sourceGlyph' in spec:
        original = font['glyf'][spec['sourceGlyph']]
        coordinates, ends, flags = original.getCoordinates(font['glyf'])
        glyph = Glyph()
        glyph.program = Program()
        glyph.program.fromBytecode([])
        glyph.coordinates, glyph.flags, glyph.endPtsOfContours = GlyphCoordinates(), array('B'), []
        begin = 0
        for index, end in enumerate(ends):
            if index in spec.get('contours', range(len(ends))):
                points = list(coordinates[begin:end + 1])
                if 'batteryLevel' in spec and index == 2:
                    points = [(round(48 + (x - 48) * spec['batteryLevel']), y) for x, y in points]
                glyph.coordinates.extend(points)
                glyph.flags.extend(flags[begin:end + 1])
                glyph.endPtsOfContours.append(len(glyph.coordinates) - 1)
            begin = end + 1
        glyph.numberOfContours = len(glyph.endPtsOfContours)
    else:
        path = pathops.Path()
        parse_path(spec['path'], path.getPen())
        path.stroke(spec['stroke'], pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
        path.convertConicsToQuads(0.01)
        path.simplify()
        pen = TTGlyphPen(None)
        path.draw(TransformPen(Cu2QuPen(pen, 0.5), (20, 0, 0, -20, 16, 434)))
        glyph = pen.glyph()
    font['glyf'][glyph_name] = glyph
    glyph.recalcBounds(font['glyf'])
    font['hmtx'].metrics[glyph_name] = (512, glyph.xMin)
    order.append(glyph_name)
    codepoints[glyph_name] = spec['codepoint']
font.setGlyphOrder(order)
assert len(set(codepoints.values())) == len(codepoints)
for name in codepoints:
    assert name in order, name
for name, target in aliases.items():
    assert target in codepoints, (name, target)
for platform, encoding in [(0, 4), (3, 10)]:
    table = next((t for t in font['cmap'].tables if t.platformID == platform and t.platEncID == encoding and t.format == 12), None)
    if table is None:
        table = CmapSubtable.newSubtable(12)
        table.platformID, table.platEncID, table.language = platform, encoding, 0
        table.cmap = {}
        font['cmap'].tables.append(table)
    table.cmap.update({cp: name for name, cp in codepoints.items()})
for record in font['name'].names:
    if record.nameID in [1, 4, 6, 16]:
        value = 'NextKdeIcons-Regular' if record.nameID == 6 else 'NextKde Icons'
        record.string = value.encode(record.getEncoding())
font.save(OUT / 'NextKdeIcons.ttf')
(OUT / 'IconMap.js').write_text('.pragma library\n// Generated by tools/icons/build_font.py; edit aliases.json/extensions.json.\nvar glyphs = '
    + json.dumps({n: chr(cp) for n, cp in codepoints.items()}, indent=2) + '\nvar aliases = '
    + json.dumps(aliases, indent=2) + '\n')
(OUT / 'provenance.json').write_text(json.dumps({
    'upstream': 'https://github.com/framework7io/framework7-icons',
    'revision': '7fb38494ba82cbef74d4f7e725431544c8ea1ee5',
    'upstreamSha256': hashlib.sha256(UPSTREAM.read_bytes()).hexdigest(),
    'fontSha256': hashlib.sha256((OUT / 'NextKdeIcons.ttf').read_bytes()).hexdigest(),
    'upstreamGlyphs': len(names), 'extensionGlyphs': len(extensions),
    'extensions': 'Original NextKde drawings and MIT Framework7-derived status contours; source in tools/icons/extensions.json',
    'extensionLicense': 'GPL-3.0-or-later', 'upstreamLicense': 'MIT',
    'tools': {'fonttools': '4.61.1', 'skia-pathops': '0.9.1'},
}, indent=2) + '\n')
print(f'Built {len(names)} upstream + {len(extensions)} extension glyphs, {len(aliases)} semantic aliases')
